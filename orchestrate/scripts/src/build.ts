// Bundles src/run.ts and a validator compiled from references/state.schema.json into scripts/run.js.
// Usage: bun build.ts [--stage]   (--stage also stages scripts/run.js; extra arguments are ignored)
import Ajv from "ajv";
import standaloneCode from "ajv/dist/standalone";
import { readFileSync } from "node:fs";
import { join } from "node:path";

const scripts = join(import.meta.dir, "..");
const schema = JSON.parse(
  readFileSync(join(scripts, "..", "references", "state.schema.json"), "utf8"),
);
const ajv = new Ajv({ allErrors: true, code: { source: true, esm: true } });
const validator = standaloneCode(ajv, ajv.compile(schema));

const result = await Bun.build({
  entrypoints: [join(import.meta.dir, "run.ts")],
  target: "bun",
  outdir: scripts,
  naming: "run.js",
  banner:
    "#!/usr/bin/env bun\n// Generated by src/build.ts from src/run.ts and references/state.schema.json. Do not edit.",
  plugins: [
    {
      name: "state-validator",
      setup(build) {
        build.onResolve({ filter: /^virtual:state-validator$/ }, () => ({
          path: "state-validator",
          namespace: "virtual",
        }));
        build.onLoad({ filter: /.*/, namespace: "virtual" }, () => ({
          contents: validator,
          loader: "js",
          resolveDir: import.meta.dir,
        }));
      },
    },
  ],
});
if (!result.success) {
  for (const log of result.logs) console.error(log);
  process.exit(1);
}
Bun.spawnSync(
  [join(scripts, "..", "..", "node_modules", ".bin", "vp"), "fmt", join(scripts, "run.js")],
  {
    stdout: "ignore",
    stderr: "inherit",
  },
);
if (process.argv.includes("--stage"))
  Bun.spawnSync(["git", "add", join(scripts, "run.js")], { stdout: "inherit", stderr: "inherit" });
console.log(`built ${join(scripts, "run.js")}`);
